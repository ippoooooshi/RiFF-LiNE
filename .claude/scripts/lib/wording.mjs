// 「まだ決まっていない書き方」を見つける語彙。**定義はここ 1 か所だけ。**
//
// なぜ切り出したか（2026-09-16）:
//   同じ「列挙が閉じていない」を、2 か所が**別々の定義**で見ていた。
//     split.mjs   /等|など|その他|(?<![0-9０-９])〜(?![0-9０-９])/
//     req-add.mjs /(など|等|その他|といった|のような)(?![0-9０-９])/g
//   「といった」「のような」は split では未閉鎖として数えられず、
//   「〜」は req-add では数えられない。**同じ語を数えているつもりで、違う数を出していた。**
//   踏んだ罠 3（2 つの検査が違う粒度を見ていた）と同じ型なので、定義を 1 つにする。
//
// 検出するのは 4 種類だけ。**どれも機械的に判定できるものに限る。**
// 「曖昧そうな語」を無限に並べると、過剰検出で検査そのものが信用されなくなる（F21）。

// 列挙が閉じていない。「〜」は数値範囲（20〜300）にも使うので、数字に挟まれたものは除く。
// **export しない。** 生の正規表現を配ると、受け取った側が自分で数え方を書ける。
// 実測（2026-09）: gate.mjs:952 と ledger.mjs:589 がそれぞれ自前で数えており、
// stripQuoted を入れてもゲートは止まり続けた。**数えるのはこのファイルの仕事。**
const OPEN_ENUM = /(など|等|その他|といった|のような|(?<![0-9０-９])〜(?![0-9０-９]))/g
export const VAGUE = /(適切に|適切な|高速に|十分な|十分に|柔軟に|必要に応じて|うまく|きちんと|なるべく|可能な限り|わかりやすく|使いやすく)/g
export const THRESHOLD_WORD = /(上限|下限|以内|以上|以下|まで|最大|最小|長さ|件数|回数|時間|秒|ミリ秒)/
export const HAS_NUMBER = /[0-9０-９]/
export const CAN_DO = /(できる|可能|する|行う|対応)/

// 上位の原文を逐語で引いた「」の中は、未閉鎖の列挙として数えない（2026-09）。
//
// 実測: 基本設計書に
//     「要件5.6「コピー／削除等」の「等」をここで解消する」
// と書いた。**「等」を閉じると宣言するために「等」を引いている**のに、
// ゲートは「等が 1 個増えた」と数えた。閉じるには引用をやめるしかなく、
// 引用をやめたら checkEvidence の逐語照合が効かなくなる。**道具どうしが噛み合っていない。**
//
// hasOpenEnum の仕事は「**下位の文書が**列挙を開けっぱなしにしていないか」。
// 上位の原文の逐語引用は下位の発言ではなく**証拠**なので、数える対象ではない。
// 「引用しただけで閉じていない」場合を捕まえるのは**判定（judge）の仕事**で、
// 要求 #ke071fc0f2999 が現に「「等」に含まれるものを確定し、項目一覧として定義する」
// と言っている。**二重に見張っている分が誤検知になっていた。**
//
// 上位の原文では「等」は地の文にあり「」の中には無い。「」の中に入るのは
// **下位が引用したときだけ**なので、この除外で上位側の検出は一切弱まらない。
//
// 残る穴（承知のうえ）: 「」で括れば黙らせられる。ただし偽の引用では
// checkEvidence の逐語照合が通らず判定も `一致` にならないので、それだけでは何も得しない。
//
// 入れ子（「…「…」…」）は内側から剥がす。対応の取れた組だけを消すので、
// 「 が片方だけ在る行を巻き込んで消しすぎることはない。
export function stripQuoted(text) {
  let t = String(text || '')
  for (let i = 0; i < 5; i++) {
    const next = t.replace(/「[^「」]*」/g, '')
    if (next === t) break
    t = next
  }
  return t
}

// 真偽だけを見たいとき（split.mjs の flags など）。`g` 付きの正規表現は
// lastIndex を持ち回るので、**test を繰り返すと結果が飛び飛びになる。**
export function hasOpenEnum(text) { return new RegExp(OPEN_ENUM.source).test(stripQuoted(text)) }

// 個数。**ゲートが HEAD と比べるときに使う。** 自前で数えないこと。
export function countOpenEnum(text) {
  return [...stripQuoted(text).matchAll(new RegExp(OPEN_ENUM.source, 'g'))].length
}

// 見つかった語（重複を除く）。**台帳が本人の答えを見るときに使う。** 自前で数えないこと。
export function openEnumWords(text) {
  return [...new Set([...stripQuoted(text).matchAll(new RegExp(OPEN_ENUM.source, 'g'))].map(m => m[1]))]
}

// 未確定点の一覧。**何を聞けばよいかまで返す。**
// 「よく質問してから書く」は規約にすると必ず形骸化するので、質問文は機械が作る。
export function inspect(text) {
  const t = String(text || '')
  const found = []

  // 列挙だけ、引用の中を除いて数える（stripQuoted の comment を参照）。
  // **程度語（VAGUE）には広げていない。** 引用で問題が出ていないうちは広げない。
  const enums = [...stripQuoted(t).matchAll(OPEN_ENUM)].map(m => m[1])
  if (enums.length) found.push({
    kind: '未閉鎖の列挙', hits: [...new Set(enums)],
    why: '列挙が閉じていないので、何が対象で何が対象外かが決まっていない',
    ask: `「${[...new Set(enums)].join('」「')}」の中身を全部挙げてください。挙げ切れないなら、この要件はまだ分割できます。`,
  })

  const vague = [...t.matchAll(VAGUE)].map(m => m[1])
  if (vague.length) found.push({
    kind: '未定義の程度', hits: [...new Set(vague)],
    why: '程度を表す語に判定条件が無いので、満たしたかどうかを誰も確かめられない',
    ask: `「${[...new Set(vague)].join('」「')}」は、何がどうなっていれば満たしたことになりますか。数値か、誰が見ても同じ判定になる条件で書いてください。`,
  })

  if (THRESHOLD_WORD.test(t) && !HAS_NUMBER.test(t)) found.push({
    kind: '数値のない閾値', hits: [t.match(THRESHOLD_WORD)[1]],
    why: '上限・範囲を語っているのに数値が無いので、実装も試験も値を決められない',
    ask: `「${t.match(THRESHOLD_WORD)[1]}」の具体的な数値を決めてください。範囲外のときにどうするか（拒否／丸める／警告）も一緒に。`,
  })

  // 「〜できる」だけで終わっていて、受入条件（どうなれば満たしたか）が無い
  const hasAccept = /(とき|場合|ならば|以外|する(と|たら)|表示され|記録され|保存され|拒否|例外|エラー)/.test(t)
  if (CAN_DO.test(t) && !hasAccept) found.push({
    kind: '受入条件が無い', hits: [],
    why: '「できる」とだけ書かれていて、何をもって満たしたと見なすかが無い。テストが書けない',
    ask: 'この機能が「できている」ことを、どんな操作をしてどうなったら確認できますか。境界（できない条件・失敗したときの挙動）も決めてください。',
  })

  return found
}
